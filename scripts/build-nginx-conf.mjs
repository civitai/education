// Turns the Cloudflare-format public/_redirects and src/data/wp-ids.json into nginx config, since the
// site is served by nginx in-cluster (Dockerfile). Writes, into the directory given as argv[2]:
//   maps.conf       http-level maps for the WordPress ?p=<id> and ?page_id=<id> shortlinks
//   redirects.conf  server-level exact-path 301s
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const out = process.argv[2] ?? 'nginx/generated';
mkdirSync(out, { recursive: true });

const q = (s) => {
  if (/["\\\s;{}$]/.test(s)) throw new Error(`Unsafe value for nginx config: ${s}`);
  return `"${s}"`;
};

const redirects = readFileSync('public/_redirects', 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => {
    const [from, to, status = '301', ...rest] = l.split(/\s+/);
    if (!from?.startsWith('/') || !to || rest.length || /[*:]/.test(from) || !/^30[1278]$/.test(status))
      throw new Error(`Unsupported _redirects rule: ${l}`);
    return `location = ${from} { return ${status} ${to}; }`;
  });

const ids = JSON.parse(readFileSync('src/data/wp-ids.json', 'utf8'));
const entries = Object.entries(ids).map(([id, path]) => `  ${q(id)} ${q(path)};`);
const map = (arg) => [`map $arg_${arg} $wp_${arg}_target {`, '  default "";', ...entries, '}'].join('\n');

// WordPress media converted to WebP when it moved into the repo: the old URL 301s to the new one.
const renames = JSON.parse(readFileSync('src/data/media-renames.json', 'utf8'));
const mediaMap = [
  'map $uri $media_rename {',
  '  default "";',
  ...Object.entries(renames).map(([from, to]) => `  ${q(from)} ${q(to)};`),
  '}',
].join('\n');

writeFileSync(
  join(out, 'maps.conf'),
  // Media paths run past 100 characters; nginx's default 64-byte map bucket refuses to start.
  `# Generated by scripts/build-nginx-conf.mjs\nmap_hash_bucket_size 256;\n${map('p')}\n${map('page_id')}\n${mediaMap}\n`,
);
writeFileSync(join(out, 'redirects.conf'), `# Generated by scripts/build-nginx-conf.mjs\n${redirects.join('\n')}\n`);
console.log(
  `nginx: ${redirects.length} redirects, ${entries.length} WordPress ids, ${Object.keys(renames).length} media renames -> ${out}`,
);
